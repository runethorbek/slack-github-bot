function jsonResponse(body: unknown, statusCode = 200): HttpResponse {
  return new HttpResponse(statusCode, new Headers(), JSON.stringify(body));
}

/** `Mock()` as a successful response. */
function okResponse(): HttpResponse {
  return jsonResponse({ id: "new-page-id" });
}

/** http_error(status_code): raise_for_status() raises an HTTPError with that status. */
function httpError(statusCode: number): HttpResponse {
  return new HttpResponse(statusCode, new Headers(), "");
}

/** `Mock().raise_for_status.side_effect = error`. */
class RaisingResponse extends HttpResponse {
  readonly error: Error;

  constructor(error: Error) {
    super(200, new Headers(), "{}");
    this.error = error;
  }

  override raise_for_status(): void {
    throw this.error;
  }
}

type Properties = Record<string, unknown>;

/** tasks_schema_response(status_options=None, priority_options=None), plus an edit hook. */
function tasksSchemaResponse(
  {
    statusOptions = null,
    priorityOptions = null,
    edit = null,
  }: {
    statusOptions?: unknown[] | null;
    priorityOptions?: unknown[] | null;
    edit?: ((properties: Properties) => void) | null;
  } = {},
): HttpResponse {
  const properties: Properties = {
    Navn: { id: "title", type: "title" },
    People: { type: "relation" },
    Track: { type: "relation" },
    Priority: {
      type: "select",
      select: { options: priorityOptions && priorityOptions.length > 0 ? priorityOptions : PRIORITY_OPTIONS },
    },
    Status: {
      type: "status",
      status: { options: statusOptions === null ? STATUS_OPTIONS : statusOptions },
    },
    "Follow-up": { type: "date" },
    Created: { type: "date" },
    Description: { type: "rich_text" },
  };
  if (edit) edit(properties);
  return jsonResponse({ properties });
}

/** tracks_response(*tracks) */
function tracksResponse(...tracks: Array<[string, string]>): HttpResponse {
  return jsonResponse({
    results: tracks.map(([trackId, name]) => ({
      id: trackId,
      properties: {
        Navn: { type: "title", title: [{ plain_text: name }] },
      },
    })),
    has_more: false,
    next_cursor: null,
  });
}

