/** submit(...): one handleAddFollowupTaskSubmission call with the test defaults. */
async function submit({
  taskName = "Send the article",
  description = "",
  followUp = "",
  priority = "",
  trackId = "",
  notionPost = null,
  notionGet = null,
  environment = ENVIRONMENT,
  personPageId = "person-page-id",
  personName = "Jane Doe",
  sleep = sleepMock(),
}: SubmitArgs = {}): Promise<[SlackMock, NotionPostMock, NotionGetMock]> {
  const postSlackMessage = slackMock();
  const post = notionPost ?? notionPostReturning(okResponse());
  const get = notionGet ?? notionGetReturning(tasksSchemaResponse());
  await handleAddFollowupTaskSubmission(
    personPageId,
    personName,
    taskName,
    description,
    followUp,
    priority,
    trackId,
    postSlackMessage,
    post,
    get,
    environment,
    { threadTs: "100.001", today: FIXED_TODAY, sleep },
  );
  return [postSlackMessage, post, get];
}

