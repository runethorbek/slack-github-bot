function parseFloatRepr(text: string): number {
  if (text === "inf") return Infinity;
  if (text === "-inf") return -Infinity;
  if (text === "nan") return NaN;
  return Number(text);
}

test("pyFloat matches float(str), including what raises", () => {
  type FloatRow = { input: string; output?: string; raises?: string };
  const failures = mismatches(golden.float as FloatRow[], (row) => {
    let got: number;
    try {
      got = pyFloat(row.input);
    } catch (error) {
      if (row.raises && error instanceof ValueError) return undefined;
      return { row, threw: String(error) };
    }
    if (row.raises) return { row, got };
    return Object.is(got, parseFloatRepr(row.output as string)) ? undefined : { row, got };
  });
  assert.deepEqual(failures, []);
});

