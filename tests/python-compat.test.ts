type Row<I, O> = { input: I; output?: O; raises?: string };

// The TS error class for each Python exception name the golden table records.
const ERROR_CLASSES: Record<string, Function> = { ValueError, OverflowError };

// Collects every mismatching row so that one failure report shows all of them.
function mismatches<R>(rows: R[], check: (row: R) => unknown): unknown[] {
  const failures: unknown[] = [];
  for (const row of rows) {
    const problem = check(row);
    if (problem !== undefined) failures.push(problem);
  }
  return failures;
}

function expectRows<I, O>(rows: Row<I, O>[], actual: (input: I) => O): unknown[] {
  return mismatches(rows, (row) => {
    let got: O;
    try {
      got = actual(row.input);
    } catch (error) {
      const expected = row.raises ? ERROR_CLASSES[row.raises] : undefined;
      return expected && error instanceof expected ? undefined : { row, threw: String(error) };
    }
    if (row.raises) return { row, got };
    try {
      assert.deepStrictEqual(got, row.output);
      return undefined;
    } catch {
      return { row, got };
    }
  });
}

