test("casefold matches Python for every code point assigned in Unicode 15.0", () => {
  const changed = new Map<number, string>(golden.casefold_all.changed);
  const unassigned: [number, number][] = golden.casefold_all.unassigned_ranges;
  let rangeIndex = 0;
  const failures: unknown[] = [];
  for (let cp = 0; cp < 0x110000; cp += 1) {
    while (rangeIndex < unassigned.length && (unassigned[rangeIndex] as [number, number])[1] < cp) {
      rangeIndex += 1;
    }
    const range = unassigned[rangeIndex];
    if (range && range[0] <= cp && cp <= range[1]) continue;
    const ch = String.fromCodePoint(cp);
    const expected = changed.get(cp) ?? ch;
    const got = casefold(ch);
    if (got !== expected) failures.push({ cp: cp.toString(16), expected, got });
  }
  assert.deepEqual(failures, []);
});

